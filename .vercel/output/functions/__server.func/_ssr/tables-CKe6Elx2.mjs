function interpolateTemp(t, insulation, buried) {
	const key = buried ? insulation === "PVC" ? "pvcSoil" : "eprSoil" : insulation === "PVC" ? "pvcAir" : "eprAir";
	const rows = TEMP_FACTOR;
	if (t <= rows[0].t) return rows[0][key];
	if (t >= rows[rows.length - 1].t) return rows[rows.length - 1][key];
	for (let i = 0; i < rows.length - 1; i++) {
		const a = rows[i];
		const b = rows[i + 1];
		if (t >= a.t && t <= b.t) {
			const fa = a[key];
			const fb = b[key];
			if (fa === 0 || fb === 0) return fa || fb;
			return fa + (t - a.t) / (b.t - a.t) * (fb - fa);
		}
	}
	return 1;
}
function groupingFactor(method, nCircuits, opts) {
	const n = Math.max(1, Math.round(nCircuits));
	if (opts?.layers && opts.layers > 1 && (method === "C" || method === "E" || method === "F")) {
		const layerKey = opts.layers >= 9 ? "9" : opts.layers >= 6 ? "6" : opts.layers >= 4 ? "4" : String(opts.layers);
		const pl = opts.perLayer ?? n;
		const col = pl >= 9 ? "9" : pl >= 6 ? "6" : pl >= 4 ? "4" : pl >= 3 ? "3" : "2";
		return {
			fa: LAYER_FACTOR[layerKey]?.[col] ?? .5,
			source: "Tabela 14 (camadas)"
		};
	}
	if (method === "D" && opts?.buriedDucts && n >= 2) {
		const table = opts.unipolar ? BURIED_UNI : BURIED_MULTI;
		const keys = Object.keys(table).map(Number).sort((a, b) => a - b);
		let row = table[n];
		if (!row) row = table[keys.reduce((p, c) => Math.abs(c - n) < Math.abs(p - n) ? c : p)];
		const si = opts.spacingM === 1 ? 3 : opts.spacingM === .5 ? 2 : opts.spacingM === .25 ? 1 : 0;
		return {
			fa: row[si],
			source: opts.unipolar ? "Tabela 17" : "Tabela 16"
		};
	}
	const idx = Math.min(12, n);
	if (method === "E" || method === "F") return {
		fa: GROUP_E_F[idx] ?? .57,
		source: "Tabela 13 · métodos E e F"
	};
	if (method === "C") return {
		fa: GROUP_C_SPACED[idx] ?? .7,
		source: "Tabela 13 · método C"
	};
	return {
		fa: GROUP_A_TO_F[idx] ?? .38,
		source: "Tabela 13 · métodos A a F"
	};
}
function ampacityOf(method, section, insulation, loaded) {
	const key = section === 1.5 ? "1.5" : String(section);
	const row = AMPACITY[method]?.[key];
	if (!row) return null;
	return row[insulation === "HEPR" ? loaded === 2 ? 0 : 1 : loaded === 2 ? 2 : 3];
}
function impedanceOf(insulation, section, formation) {
	const key = section === 1.5 ? "1.5" : String(section);
	const form = formation === "4x1" ? "4x1" : formation === "1x4" ? "1x4" : formation;
	const row = IMPEDANCE[insulation]?.[key]?.[form] ?? IMPEDANCE[insulation]?.[key]?.["3x1"];
	if (!row || row.rca == null) return null;
	return {
		rca: row.rca,
		xl: row.xl ?? .1
	};
}
function cableOd(section, formation) {
	const map = CABLE_OD[section === 1.5 ? "1.5" : String(section)];
	if (!map) return null;
	return map[formation] ?? map["3x1"] ?? map["1x3"] ?? null;
}
